export const exportAsXLSX = (title: string, textContent: string) => {
  const csvContent = `ID,Topic,Summary,Status\n1,${title},"${textContent.slice(0, 100).replace(/"/g, '""')}",COMPLETED\n`;
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  downloadFile(blob, `${title.toLowerCase().replace(/\s+/g, '_')}.xlsx`);
};

export const exportAsZIP = (title: string, codeSnippet: string) => {
  const projectArchive = `
# Project Archive: ${title}
# Generated by StudyX Claude-Level AI Assistant

=== File: index.js ===
${codeSnippet}

=== File: README.md ===
# ${title}
This code project was generated automatically by StudyX AI Assistant.
  `;
  const blob = new Blob([projectArchive], { type: 'application/zip' });
  downloadFile(blob, `${title.toLowerCase().replace(/\s+/g, '_')}_project.zip`);
};

export const exportCodeFile = (title: string, codeSnippet: string, extension: string = 'ts') => {
  const blob = new Blob([codeSnippet], { type: 'text/plain;charset=utf-8;' });
  downloadFile(blob, `${title.toLowerCase().replace(/\s+/g, '_')}.${extension}`);
};
