// File Exporter Utility for StudyX Claude-Level AI Assistant

export const downloadFile = (blob: Blob, filename: string) => {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

export const exportAsPDF = (title: string, textContent: string) => {
  const htmlContent = `
    <!DOCTYPE html>
    <html>
    <head>
      <title>${title}</title>
      <style>
        body { font-family: Arial, sans-serif; padding: 40px; color: #111; line-height: 1.6; }
        h1 { color: #5B21B6; border-bottom: 2px solid #DDD; padding-bottom: 10px; }
        pre { background: #F3F4F6; padding: 15px; border-radius: 8px; font-family: monospace; }
        footer { margin-top: 50px; font-size: 12px; color: #666; border-top: 1px solid #EEE; padding-top: 10px; }
      </style>
    </head>
    <body>
      <h1>${title}</h1>
      <div>${textContent.replace(/\n/g, '<br/>')}</div>
      <footer>Generated by StudyX Claude-Level AI Assistant</footer>
    </body>
    </html>
  `;
  const blob = new Blob([htmlContent], { type: 'application/pdf' });
  downloadFile(blob, `${title.toLowerCase().replace(/\s+/g, '_')}.pdf`);
};

